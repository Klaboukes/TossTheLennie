const DUTCH = new Set(Object.values(NL));
const NUMBER = /\d+(?:[.,]\d+)*/g;

function initialLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'nl' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  return (navigator.languages ?? [navigator.language]).some((l) => /^nl\b/i.test(l ?? '')) ? 'nl' : 'en';
}

export let lang = initialLang();

/** English texts that had no Dutch version when they came up (look in the console: `i18nMissing`). */
const missing = new Set();
window.i18nMissing = missing;

/** `text` in the current language, with `{name}` bits filled in from `vars`. */
export function t(text, vars) {
  if (text == null) return text;
  text = String(text);
  let out = text;
  if (lang === 'nl') {
    if (Object.hasOwn(NL, text)) out = NL[text];
    else if (!DUTCH.has(text)) {
      const numbers = text.match(NUMBER);
      const pattern = numbers && text.replace(NUMBER, '{n}');
      if (numbers && Object.hasOwn(NL, pattern)) {
        let i = 0;
        out = NL[pattern].replace(/\{n\}/g, () => numbers[i++]);
      } else if (/[a-z].*[a-z]/i.test(text)) {
        missing.add(text);
      }
    }
  }
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(vars, k) ? vars[k] : m));
  return out;
}

/** A whole number written the local way: 2,500 in English, 2.500 in Dutch. */
export const fmt = (n) => Math.round(n).toLocaleString(lang === 'nl' ? 'nl-NL' : 'en-US');
/** A number with `digits` decimals written the local way: 1.50 in English, 1,50 in Dutch. */
export const fixed = (n, digits) => (lang === 'nl' ? n.toFixed(digits).replace('.', ',') : n.toFixed(digits));

// ---------------------------------------------------------------- the page's own texts
// The texts written in index.html, remembered in English when the page loads, so
// they can be put in either language. Elements marked translate="no" are left
// alone; data-i18n="html" translates an element's whole inner HTML in one go
// (for a sentence with bold words in it).
const ATTRS = ['title', 'aria-label', 'data-tip', 'placeholder'];
const pageTexts = [];
const squash = (s) => s.replace(/\s+/g, ' ').trim();

function collect() {
  const skip = (el) => el.closest('[translate="no"], script, style, noscript');
  for (const el of document.body.querySelectorAll('[data-i18n="html"]')) {
    if (!skip(el)) pageTexts.push({ el, html: squash(el.innerHTML) });
  }
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node; (node = walker.nextNode());) {
    const el = node.parentElement;
    if (!/[a-z]/i.test(node.nodeValue) || skip(el) || el.closest('[data-i18n="html"]')) continue;
    const [, before, words, after] = node.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
    pageTexts.push({ node, before, words: squash(words), after });
  }
  for (const el of document.body.querySelectorAll(ATTRS.map((a) => `[${a}]`).join(','))) {
    if (skip(el)) continue;
    for (const attr of ATTRS) if (el.hasAttribute(attr)) pageTexts.push({ el, attr, value: el.getAttribute(attr) });
  }
}

function translatePage() {
  document.documentElement.lang = lang;
  for (const p of pageTexts) {
    if (p.html !== undefined) p.el.innerHTML = t(p.html);
    else if (p.node) p.node.nodeValue = p.before + t(p.words) + p.after;
    else p.el.setAttribute(p.attr, t(p.value));
  }
}

collect();
if (lang !== 'en') translatePage();

const listeners = [];
/** `fn` runs after each language switch, to redo the texts the game writes itself. */
export function onLangChange(fn) {
  listeners.push(fn);
}

export function setLang(next) {
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  translatePage();
  for (const fn of listeners) fn();
}
